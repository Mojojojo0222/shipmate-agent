package com.shipmate.service;

import com.shipmate.config.AgentProperties;
import com.shipmate.model.App;
import org.springframework.stereotype.Service;

import java.util.LinkedHashMap;
import java.util.Map;

@Service
public class ManifestGenerator {

    private final AgentProperties props;

    public ManifestGenerator(AgentProperties props) {
        this.props = props;
    }

    private String imageRepository(App app) {
        return props.getRegistry().getUrl() + "/" + props.getRegistry().getOwner().toLowerCase() + "/" + app.getName();
    }

    public Map<String, String> generateHelmChart(App app, CostEstimator.Sizing sizing) {
        Map<String, String> files = new LinkedHashMap<>();
        String base = props.getGitops().getManifestsPath() + "/" + app.getName() + "/helm";
        boolean mysql = "mysql".equals(app.getDbEngine());
        int dbPort = mysql ? 3306 : 5432;
        String dbImage = mysql ? "mysql:8.4" : "postgres:16-alpine";
        String dbDir = mysql ? "/var/lib/mysql" : "/var/lib/postgresql/data";

        files.put(base + "/Chart.yaml", """
                apiVersion: v2
                name: %s
                description: Generated by Shipmate
                type: application
                version: 0.1.0
                """.formatted(app.getName()));

        files.put(base + "/values.yaml", """
                image:
                  repository: %s
                  tag: latest
                  pullPolicy: Always

                app:
                  name: %s
                  namespace: %s
                  replicas: %d
                  port: %d
                  serviceType: %s
                  healthPath: /actuator/health
                  resources:
                    requests:
                      cpu: %dm
                      memory: %dMi
                    limits:
                      cpu: %dm
                      memory: %dMi
                  hpa:
                    enabled: true
                    minReplicas: %d
                    maxReplicas: %d
                    cpuTarget: 60

                db:
                  engine: %s
                  storage: %dGi
                  port: %d
                """.formatted(
                imageRepository(app),
                app.getName(),
                app.getNamespace(),
                sizing.replicas,
                app.getContainerPort(),
                props.getK8s().getServiceType(),
                Math.max(500, sizing.vcpu * 500),
                sizing.memoryGiB * 1024,
                Math.max(1000, sizing.vcpu * 1000),
                sizing.memoryGiB * 1536,
                sizing.replicas,
                sizing.maxReplicas,
                mysql ? "mysql" : "postgres",
                sizing.dbStorageGiB,
                dbPort));

        files.put(base + "/templates/deployment.yaml", """
                apiVersion: apps/v1
                kind: Deployment
                metadata:
                  name: {{ .Values.app.name }}
                  namespace: {{ .Values.app.namespace }}
                  labels:
                    app: {{ .Values.app.name }}
                spec:
                  replicas: {{ .Values.app.replicas }}
                  selector:
                    matchLabels:
                      app: {{ .Values.app.name }}
                  template:
                    metadata:
                      labels:
                        app: {{ .Values.app.name }}
                    spec:
                      containers:
                        - name: {{ .Values.app.name }}
                          image: "{{ .Values.image.repository }}:{{ .Values.image.tag }}"
                          imagePullPolicy: {{ .Values.image.pullPolicy }}
                          ports:
                            - containerPort: {{ .Values.app.port }}
                          readinessProbe:
                            httpGet:
                              path: {{ .Values.app.healthPath }}
                              port: {{ .Values.app.port }}
                            initialDelaySeconds: 150
                            periodSeconds: 10
                            timeoutSeconds: 3
                            failureThreshold: 5
                          livenessProbe:
                            httpGet:
                              path: {{ .Values.app.healthPath }}
                              port: {{ .Values.app.port }}
                            initialDelaySeconds: 300
                            periodSeconds: 15
                            timeoutSeconds: 3
                            failureThreshold: 5
                          env:
                            - name: PORT
                              value: "{{ .Values.app.port }}"
                            - name: DB_HOST
                              value: {{ .Values.app.name }}-db
                            - name: DB_PORT
                              value: "{{ .Values.db.port }}"
                            - name: DB_NAME
                              value: app
                            - name: DB_USER
                              value: app
                            - name: DB_PASS
                              value: app
                          resources:
                            requests:
                              cpu: {{ .Values.app.resources.requests.cpu }}
                              memory: {{ .Values.app.resources.requests.memory }}
                            limits:
                              cpu: {{ .Values.app.resources.limits.cpu }}
                              memory: {{ .Values.app.resources.limits.memory }}
                """);

        files.put(base + "/templates/service.yaml", """
                apiVersion: v1
                kind: Service
                metadata:
                  name: {{ .Values.app.name }}
                  namespace: {{ .Values.app.namespace }}
                  labels:
                    app: {{ .Values.app.name }}
                spec:
                  type: {{ .Values.app.serviceType }}
                  selector:
                    app: {{ .Values.app.name }}
                  ports:
                    - port: 80
                      targetPort: {{ .Values.app.port }}
                """);

        files.put(base + "/templates/hpa.yaml", """
                apiVersion: autoscaling/v2
                kind: HorizontalPodAutoscaler
                metadata:
                  name: {{ .Values.app.name }}
                  namespace: {{ .Values.app.namespace }}
                spec:
                  scaleTargetRef:
                    apiVersion: apps/v1
                    kind: Deployment
                    name: {{ .Values.app.name }}
                  minReplicas: {{ .Values.app.hpa.minReplicas }}
                  maxReplicas: {{ .Values.app.hpa.maxReplicas }}
                  metrics:
                    - type: Resource
                      resource:
                        name: cpu
                        target:
                          type: Utilization
                          averageUtilization: {{ .Values.app.hpa.cpuTarget }}
                """);

        files.put(base + "/templates/namespace.yaml", """
                apiVersion: v1
                kind: Namespace
                metadata:
                  name: {{ .Values.app.namespace }}
                """);

        files.put(base + "/templates/database.yaml", """
                apiVersion: v1
                kind: Service
                metadata:
                  name: {{ .Values.app.name }}-db
                  namespace: {{ .Values.app.namespace }}
                spec:
                  selector:
                    app: {{ .Values.app.name }}-db
                  ports:
                    - port: {{ .Values.db.port }}
                      targetPort: {{ .Values.db.port }}
                ---
                apiVersion: apps/v1
                kind: StatefulSet
                metadata:
                  name: {{ .Values.app.name }}-db
                  namespace: {{ .Values.app.namespace }}
                spec:
                  serviceName: {{ .Values.app.name }}-db
                  replicas: 1
                  selector:
                    matchLabels:
                      app: {{ .Values.app.name }}-db
                  template:
                    metadata:
                      labels:
                        app: {{ .Values.app.name }}-db
                    spec:
                      containers:
                        - name: %s
                          image: %s
                          env:
                %s          ports:
                            - containerPort: {{ .Values.db.port }}
                          volumeMounts:
                            - name: data
                              mountPath: %s
                  volumeClaimTemplates:
                    - metadata:
                        name: data
                      spec:
                        accessModes: ["ReadWriteOnce"]
                        resources:
                          requests:
                            storage: {{ .Values.db.storage }}
                """.formatted(mysql ? "mysql" : "postgres", dbImage, dbEnvBlock(mysql), dbDir));

        return files;
    }

    public Map<String, String> generateHelmChartWithDb(App app, CostEstimator.Sizing sizing) {
        return generateHelmChart(app, sizing);
    }

    private String dbEnvBlock(boolean mysql) {
        if (mysql) {
            return """
            - name: MYSQL_ROOT_PASSWORD
              value: root
            - name: MYSQL_DATABASE
              value: app
            - name: MYSQL_USER
              value: app
            - name: MYSQL_PASSWORD
              value: app
""";
        }
        return """
            - name: POSTGRES_USER
              value: app
            - name: POSTGRES_PASSWORD
              value: app
            - name: POSTGRES_DB
              value: app
""";
    }

    public String generateArgoApp(App app) {
        String base = props.getGitops().getManifestsPath() + "/" + app.getName();
        return """
                apiVersion: argoproj.io/v1alpha1
                kind: Application
                metadata:
                  name: %s
                  namespace: argocd
                spec:
                  project: default
                  source:
                    repoURL: %s
                    targetRevision: HEAD
                    path: %s/helm
                  destination:
                    server: https://kubernetes.default.svc
                    namespace: %s
                  syncPolicy:
                    automated:
                      prune: true
                      selfHeal: true
                    syncOptions:
                      - CreateNamespace=true
                  ignoreDifferences:
                    - group: apps
                      kind: Deployment
                      jsonPointers:
                        - /spec/replicas
                """.formatted(app.getName(), app.getRepoUrl(), base, app.getNamespace());
    }

    public String generateCiWorkflow(App app) {
        String chartPath = props.getGitops().getManifestsPath() + "/" + app.getName() + "/helm/values.yaml";
        String image = imageRepository(app);
        if ("ecr".equalsIgnoreCase(props.getRegistry().getType())) {
            return generateEcrWorkflow(app, chartPath, image);
        }
        return generateGhcrWorkflow(app, chartPath, image);
    }

    private String generateGhcrWorkflow(App app, String chartPath, String image) {
        return """
                name: shipmate-deploy

                on:
                  workflow_dispatch:

                env:
                  CHART_VALUES: %s

                jobs:
                  build-and-push:
                    runs-on: ubuntu-latest
                    permissions:
                      contents: write
                      packages: write
                    steps:
                      - name: Checkout
                        uses: actions/checkout@v4
                        with:
                          fetch-depth: 0
                      - name: Login to GHCR
                        uses: docker/login-action@v3
                        with:
                          registry: %s
                          username: ${{ github.actor }}
                          password: ${{ secrets.GITHUB_TOKEN }}
                      - name: Build and push image
                        env:
                          IMAGE_TAG: ${{ github.sha }}
                        run: |
                          docker build -t %s:$IMAGE_TAG .
                          docker push %s:$IMAGE_TAG
                      - name: Bump chart tag
                        env:
                          IMAGE_TAG: ${{ github.sha }}
                        run: |
                          if grep -q '^  tag:' "$CHART_VALUES"; then
                            sed -i "s|^  tag:.*|  tag: $IMAGE_TAG|" "$CHART_VALUES"
                          else
                            sed -i "s|^  pullPolicy: Always|  pullPolicy: Always\\n  tag: $IMAGE_TAG|" "$CHART_VALUES"
                          fi
                          git config user.name "shipmate-bot"
                          git config user.email "shipmate@users.noreply.github.com"
                          git add "$CHART_VALUES"
                          git commit -m "chore: shipmate bump tag to $IMAGE_TAG [skip ci]"
                          for i in 1 2 3; do
                            if git push origin HEAD:${{ github.ref_name }}; then
                              exit 0
                            fi
                            git fetch origin ${{ github.ref_name }}
                            git rebase origin/${{ github.ref_name }}
                          done
                          git push origin HEAD:${{ github.ref_name }}
                """.formatted(chartPath, props.getRegistry().getUrl(), image, image);
    }

    private String generateEcrWorkflow(App app, String chartPath, String image) {
        String roleArn = props.getAws().getGithubActionsRoleArn();
        return """
                name: shipmate-deploy

                on:
                  workflow_dispatch:

                env:
                  AWS_REGION: %s
                  ECR_REPOSITORY: %s
                  CHART_VALUES: %s

                jobs:
                  build-and-push:
                    runs-on: ubuntu-latest
                    permissions:
                      id-token: write
                      contents: write
                    steps:
                      - name: Checkout
                        uses: actions/checkout@v4
                        with:
                          fetch-depth: 0
                      - name: Configure AWS credentials
                        uses: aws-actions/configure-aws-credentials@v4
                        with:
                          role-to-assume: %s
                          aws-region: ${{ env.AWS_REGION }}
                          role-session-name: shipmate-deploy
                      - name: Login to Amazon ECR
                        uses: aws-actions/amazon-ecr-login@v2
                      - name: Build and push image
                        env:
                          IMAGE_TAG: ${{ github.sha }}
                        run: |
                          docker build -t $ECR_REGISTRY/$ECR_REPOSITORY:$IMAGE_TAG .
                          docker push $ECR_REGISTRY/$ECR_REPOSITORY:$IMAGE_TAG
                      - name: Bump chart tag
                        env:
                          IMAGE_TAG: ${{ github.sha }}
                        run: |
                          if grep -q '^  tag:' "$CHART_VALUES"; then
                            sed -i "s|^  tag:.*|  tag: $IMAGE_TAG|" "$CHART_VALUES"
                          else
                            sed -i "s|^  pullPolicy: Always|  pullPolicy: Always\\n  tag: $IMAGE_TAG|" "$CHART_VALUES"
                          fi
                          git config user.name "shipmate-bot"
                          git config user.email "shipmate@users.noreply.github.com"
                          git add "$CHART_VALUES"
                          git commit -m "chore: shipmate bump tag to $IMAGE_TAG [skip ci]"
                          for i in 1 2 3; do
                            if git push origin HEAD:${{ github.ref_name }}; then
                              exit 0
                            fi
                            git fetch origin ${{ github.ref_name }}
                            git rebase origin/${{ github.ref_name }}
                          done
                          git push origin HEAD:${{ github.ref_name }}
                """.formatted(props.getAws().getRegion(), props.getAws().getEcrRepositoryPrefix() + "-" + app.getName(),
                chartPath, roleArn);
    }
}
